# RULES AND NAMING CONVENTIONS OF VARIABLES IN PYTHON
# 1) Variable names must not begin with a number, they can only start with a letter or underscore. E.g 2sports = "Football, swimming" - wrong
# sports = "Football, swimming" - right
# _sports = "Football, swimming" - right

# 2) Variable names can only contain letters, numbers and underscores. They can begin with letters and underscores but should never begin with numbers. . E.g 
five_2_types_of_sports = "Volleyball, Swimming"

# 3) Variables containing more than one word should be separated by an underscore i.e the snake case naming convention. E.g
tech_school = "Learn 2 Earn"
place_of_work = "Naelix"

# 4) Variable’s names must not be one of Python’s reserved keywords e.g if, def, e.t.c E.g
# def = "function definition keyword"

# 5) Variable names must be descriptive. One should immediately understand what a variable’s for by it’s name.
school_time = 8
isloggedin = True

# 6) Avoid using single letter variable names. Though it's accepted in python, it doesn't explain what the variable's for.
x = 60
b = 50 - 100

# 7) Variable names are case sensitive. The 3 variables below are treated as different variables
age = 25
Age = 25
AGE = 25
